import React, { useMemo, useState } from 'react';
import {
  ChevronDown,
  Download,
  FileBarChart2,
  FileText,
  Printer,
  Sprout,
  Waves,
  X,
} from 'lucide-react';
import {
  CartesianGrid,
  Cell,
  Line,
  LineChart,
  Pie,
  PieChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts';
import {
  CHANGE_TYPES_BREAKDOWN,
  LAND_COVER_SERIES,
  RECENT_REPORTS,
} from '../data/earthDatasets';
import type { ReportRecord } from '../types/geospatial';

const REPORT_TIMEFRAMES = ['Last Year', 'Last 6 Months', 'Q3–Q4 2026', 'All Time'];

export const ReportsPage: React.FC = () => {
  const [timeframe, setTimeframe] = useState<string>('Last Year');
  const [previewReport, setPreviewReport] = useState<ReportRecord | null>(null);
  const [visibleSeries, setVisibleSeries] = useState({
    forest: true,
    urban: true,
    water: true,
    other: true,
  });

  const seriesKey =
    timeframe === 'All Time' ? 'Last Year' : timeframe;
  const lineData = LAND_COVER_SERIES[seriesKey] ?? LAND_COVER_SERIES['Last Year'];
  const pieData =
    CHANGE_TYPES_BREAKDOWN[seriesKey] ?? CHANGE_TYPES_BREAKDOWN['Last Year'];

  const filteredReports = useMemo(() => {
    if (timeframe === 'All Time' || timeframe === 'Last Year') {
      return RECENT_REPORTS;
    }
    return RECENT_REPORTS.filter((r) => r.timeframe === timeframe);
  }, [timeframe]);

  const handleExportPdf = () => {
    window.print();
  };

  const handleDownloadReport = (report: ReportRecord) => {
    const content = [
      `ANTHARIKSH – EARTH OBSERVATION REPORT`,
      `==================================================`,
      `Title:       ${report.title}`,
      `Location:    ${report.location}`,
      `Category:    ${report.category}`,
      `Date:        ${report.date}`,
      `Methodology: ${report.methodology}`,
      ``,
      `Summary:`,
      report.summary,
      ``,
      `Key Metrics:`,
      ...report.keyMetrics.map((m) => `- ${m.label}: ${m.value}`),
      ``,
      `Generated by ANTHARIKSH Earth Intelligence Platform (Reference Analytics).`,
    ].join('\n');

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${report.id}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const getCategoryIcon = (cat: ReportRecord['category']) => {
    if (cat === 'Flood Risk') return Waves;
    if (cat === 'Vegetation') return Sprout;
    if (cat === 'Historical') return FileBarChart2;
    return FileText;
  };

  return (
    <div className="px-5 py-6 lg:px-8 lg:py-7 space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-end justify-between gap-4">
        <div>
          <h1 className="font-display text-3xl sm:text-4xl font-semibold text-[#F5F0E6]">
            Reports &amp; Analytics
          </h1>
          <p className="mt-1 text-sm text-[#9AA6B2]">
            View detailed reports, analytics and export valuable insights.
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-2.5 no-print">
          <div className="relative">
            <select
              aria-label="Filter reports by date range"
              value={timeframe}
              onChange={(e) => setTimeframe(e.target.value)}
              className="appearance-none rounded-xl border border-white/[0.1] bg-[#0D151B] py-2 pl-3.5 pr-8 text-xs font-medium text-[#F2EDE4] focus:border-[#E5A94C]/50 focus:outline-none"
            >
              {REPORT_TIMEFRAMES.map((tf) => (
                <option key={tf} value={tf}>
                  {tf}
                </option>
              ))}
            </select>
            <ChevronDown className="pointer-events-none absolute right-2.5 top-2.5 h-3.5 w-3.5 text-[#8E9BA6]" />
          </div>

          <button
            type="button"
            onClick={handleExportPdf}
            className="inline-flex items-center gap-2 rounded-xl bg-[#E8DCC4] px-4 py-2 text-xs font-semibold text-[#0A1015] hover:bg-[#F3E9D6] transition-colors whitespace-nowrap"
          >
            <Printer className="h-3.5 w-3.5" />
            <span>Export PDF</span>
          </button>
        </div>
      </div>

      {/* Charts Row matching Reference */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-5">
        {/* Land Cover Change Multi-Line Chart */}
        <div className="lg:col-span-7 rounded-2xl border border-white/[0.08] bg-[#0B1217] p-5 space-y-4">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <h2 className="text-sm font-semibold text-[#F5F0E6]">
              Land Cover Change
            </h2>

            <div className="flex flex-wrap items-center gap-3 text-xs">
              {[
                { key: 'forest', label: 'Forest', color: '#5EA86E' },
                { key: 'urban', label: 'Urban', color: '#E5A94C' },
                { key: 'water', label: 'Water', color: '#5CA4B8' },
                { key: 'other', label: 'Other', color: '#94A3B8' },
              ].map((s) => {
                const k = s.key as keyof typeof visibleSeries;
                const active = visibleSeries[k];
                return (
                  <button
                    key={s.key}
                    type="button"
                    onClick={() =>
                      setVisibleSeries((prev) => ({ ...prev, [k]: !prev[k] }))
                    }
                    className={`inline-flex items-center gap-1.5 transition-opacity ${
                      active ? 'opacity-100 text-[#D2DCE4]' : 'opacity-40 text-[#6C7883]'
                    }`}
                  >
                    <span
                      className="h-2 w-2 rounded-full"
                      style={{ backgroundColor: s.color }}
                    />
                    <span>{s.label}</span>
                  </button>
                );
              })}
            </div>
          </div>

          <div className="h-[240px] w-full">
            <ResponsiveContainer width="100%" height="100%">
              <LineChart
                data={lineData}
                margin={{ top: 8, right: 12, left: -18, bottom: 0 }}
              >
                <CartesianGrid
                  stroke="rgba(255,255,255,0.06)"
                  strokeDasharray="3 3"
                  vertical={false}
                />
                <XAxis
                  dataKey="month"
                  tick={{ fill: '#8E9BA6', fontSize: 11 }}
                  axisLine={{ stroke: 'rgba(255,255,255,0.1)' }}
                  tickLine={false}
                />
                <YAxis
                  tick={{ fill: '#8E9BA6', fontSize: 11 }}
                  axisLine={false}
                  tickLine={false}
                />
                <Tooltip
                  contentStyle={{
                    backgroundColor: '#0D151B',
                    border: '1px solid rgba(255,255,255,0.12)',
                    borderRadius: '10px',
                    fontSize: '12px',
                    color: '#F2EDE4',
                  }}
                />
                {visibleSeries.forest && (
                  <Line
                    type="monotone"
                    dataKey="forest"
                    name="Forest Index"
                    stroke="#5EA86E"
                    strokeWidth={2}
                    dot={false}
                  />
                )}
                {visibleSeries.urban && (
                  <Line
                    type="monotone"
                    dataKey="urban"
                    name="Urban Index"
                    stroke="#E5A94C"
                    strokeWidth={2}
                    dot={false}
                  />
                )}
                {visibleSeries.water && (
                  <Line
                    type="monotone"
                    dataKey="water"
                    name="Water Index"
                    stroke="#5CA4B8"
                    strokeWidth={2}
                    dot={false}
                  />
                )}
                {visibleSeries.other && (
                  <Line
                    type="monotone"
                    dataKey="other"
                    name="Other Surface"
                    stroke="#94A3B8"
                    strokeWidth={1.75}
                    dot={false}
                  />
                )}
              </LineChart>
            </ResponsiveContainer>
          </div>
        </div>

        {/* Change Types Donut Chart */}
        <div className="lg:col-span-5 rounded-2xl border border-white/[0.08] bg-[#0B1217] p-5 flex flex-col justify-between">
          <div>
            <h2 className="text-sm font-semibold text-[#F5F0E6]">
              Change Types
            </h2>
            <p className="mt-0.5 text-xs text-[#8E9BA6]">
              Distribution across {seriesKey}
            </p>
          </div>

          <div className="flex flex-col sm:flex-row items-center justify-between gap-4 py-2">
            <div className="h-[200px] w-[200px]">
              <ResponsiveContainer width="100%" height="100%">
                <PieChart>
                  <Pie
                    data={pieData}
                    dataKey="value"
                    nameKey="name"
                    cx="50%"
                    cy="50%"
                    innerRadius={56}
                    outerRadius={84}
                    paddingAngle={3}
                    stroke="none"
                  >
                    {pieData.map((entry) => (
                      <Cell key={entry.name} fill={entry.color} />
                    ))}
                  </Pie>
                  <Tooltip
                    contentStyle={{
                      backgroundColor: '#0D151B',
                      border: '1px solid rgba(255,255,255,0.12)',
                      borderRadius: '10px',
                      fontSize: '12px',
                      color: '#F2EDE4',
                    }}
                    formatter={(value) => [`${value}%`, 'Share']}
                  />
                </PieChart>
              </ResponsiveContainer>
            </div>

            <div className="space-y-3 flex-1 w-full sm:w-auto">
              {pieData.map((item) => (
                <div
                  key={item.name}
                  className="flex items-center justify-between gap-4 text-xs"
                >
                  <span className="flex items-center gap-2 text-[#D2DCE4]">
                    <span
                      className="h-2.5 w-2.5 rounded-full shrink-0"
                      style={{ backgroundColor: item.color }}
                    />
                    <span>{item.name}</span>
                  </span>
                  <span className="font-mono-tabular font-semibold text-[#F5F0E6]">
                    {item.value}%
                  </span>
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>

      {/* Recent Reports List */}
      <section className="rounded-2xl border border-white/[0.08] bg-[#0B1217] p-5 space-y-3">
        <div className="flex items-center justify-between">
          <h2 className="text-sm font-semibold text-[#F5F0E6]">
            Recent Reports
          </h2>
          <span className="text-xs font-mono-tabular text-[#8E9BA6]">
            {filteredReports.length} reports
          </span>
        </div>

        <div className="divide-y divide-white/[0.06]">
          {filteredReports.map((rep) => {
            const Icon = getCategoryIcon(rep.category);
            return (
              <div
                key={rep.id}
                className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 py-3.5 first:pt-1 last:pb-1"
              >
                <button
                  type="button"
                  onClick={() => setPreviewReport(rep)}
                  className="flex items-center gap-3 text-left group min-w-0"
                >
                  <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg border border-white/[0.08] bg-[#101820] text-[#E5A94C] group-hover:border-[#E5A94C]/40">
                    <Icon className="h-4 w-4" />
                  </div>
                  <div className="min-w-0">
                    <div className="text-sm font-medium text-[#F2EDE4] group-hover:text-[#E5A94C] transition-colors truncate">
                      {rep.title}
                    </div>
                    <div className="text-xs text-[#8E9BA6] truncate">
                      {rep.category} · {rep.methodology}
                    </div>
                  </div>
                </button>

                <div className="flex items-center justify-between sm:justify-end gap-4 shrink-0 no-print">
                  <span className="text-xs font-mono-tabular text-[#8E9BA6]">
                    {rep.date}
                  </span>
                  <button
                    type="button"
                    onClick={() => handleDownloadReport(rep)}
                    className="inline-flex items-center gap-1.5 rounded-lg bg-[#E8DCC4] px-3.5 py-1.5 text-xs font-semibold text-[#0A1015] hover:bg-[#F3E9D6] transition-colors"
                  >
                    <Download className="h-3.5 w-3.5" />
                    <span>Download</span>
                  </button>
                </div>
              </div>
            );
          })}
        </div>
      </section>

      {/* Report Detail Preview Modal */}
      {previewReport && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 p-4 backdrop-blur-xs no-print">
          <div className="w-full max-w-xl rounded-2xl border border-white/15 bg-[#0D151B] p-6 shadow-2xl space-y-4">
            <div className="flex items-start justify-between gap-4">
              <div>
                <div className="text-xs font-mono-tabular text-[#E5A94C]">
                  {previewReport.category} · {previewReport.date}
                </div>
                <h3 className="mt-1 font-display text-xl font-semibold text-[#F5F0E6]">
                  {previewReport.title}
                </h3>
              </div>
              <button
                type="button"
                onClick={() => setPreviewReport(null)}
                aria-label="Close report preview"
                className="rounded-lg p-1.5 text-[#8E9BA6] hover:bg-white/5 hover:text-[#F2EDE4]"
              >
                <X className="h-4 w-4" />
              </button>
            </div>

            <p className="text-sm leading-relaxed text-[#9AA6B2]">
              {previewReport.summary}
            </p>

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
              {previewReport.keyMetrics.map((m) => (
                <div
                  key={m.label}
                  className="rounded-xl border border-white/[0.08] bg-[#111B22] p-3"
                >
                  <div className="text-[11px] text-[#8E9BA6]">{m.label}</div>
                  <div className="mt-1 text-sm font-semibold font-mono-tabular text-[#F2EDE4]">
                    {m.value}
                  </div>
                </div>
              ))}
            </div>

            <div className="text-xs text-[#8E9BA6] border-t border-white/[0.08] pt-3">
              Methodology: {previewReport.methodology}
            </div>

            <div className="flex justify-end gap-2.5 pt-1">
              <button
                type="button"
                onClick={() => {
                  setPreviewReport(null);
                  setTimeout(() => window.print(), 100);
                }}
                className="inline-flex items-center gap-1.5 rounded-lg border border-white/15 bg-[#121B22] px-3.5 py-2 text-xs font-medium text-[#F2EDE4] hover:border-[#E5A94C]/45"
              >
                <Printer className="h-3.5 w-3.5 text-[#E5A94C]" />
                <span>Print PDF</span>
              </button>
              <button
                type="button"
                onClick={() => handleDownloadReport(previewReport)}
                className="inline-flex items-center gap-1.5 rounded-lg bg-[#E8DCC4] px-4 py-2 text-xs font-semibold text-[#0A1015] hover:bg-[#F3E9D6]"
              >
                <Download className="h-3.5 w-3.5" />
                <span>Download Report</span>
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
